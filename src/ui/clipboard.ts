// Copying text, also where the Clipboard API is missing: pages served over plain http from
// another address (the dev server opened by IP) don't get navigator.clipboard at all.

/** Copies text; resolves to false if the browser wouldn't allow it. Call from a click. */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // Not allowed (e.g. the page isn't focused): try the old way.
  }
  const area = document.createElement("textarea");
  area.value = text;
  area.setAttribute("readonly", "");
  area.style.position = "fixed";
  area.style.opacity = "0";
  document.body.appendChild(area);
  area.select();
  let ok = false;
  try {
    ok = document.execCommand("copy");
  } catch {
    ok = false;
  }
  area.remove();
  return ok;
}
